// Compile the shared source for the published CommonJS package. No runtime
// dependency on the private runtimed workspace package is shipped.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const source = path.join(root, "packages/runtimed/src/execution-store.ts");
const output = path.join(root, "packages/runtimed-node/src");
const program = ts.createProgram([source], {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.CommonJS,
  declaration: true,
  strict: true,
  skipLibCheck: true,
  types: [],
});
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length) {
  console.error(
    ts.formatDiagnosticsWithColorAndContext(diagnostics, {
      getCanonicalFileName: (name) => name,
      getCurrentDirectory: () => root,
      getNewLine: () => "\n",
    }),
  );
  process.exit(1);
}
const check = process.argv.includes("--check");
let stale = false;
program.emit(undefined, (name, content) => {
  const filename = name.endsWith(".d.ts") ? "execution-store.d.cts" : "execution-store.cjs";
  const destination = path.join(output, filename);
  const generated = "// Generated by scripts/build-execution-store.mjs. Do not edit.\n" + content;
  if (check) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== generated) {
      console.error(`${filename} is stale; run pnpm --dir packages/runtimed-node build:stores`);
      stale = true;
    }
  } else fs.writeFileSync(destination, generated);
});
if (stale) process.exit(1);
